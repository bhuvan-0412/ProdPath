const TONE = {
  // ink at ~6% on paper; the ink token turns cream in dark mode, shown at ~8%
  ink: 'text-ink/[0.06] dark:text-ink/[0.08]',
  cream: 'text-[#F6F1E7]/[0.08]',
};

// Clipped to its (relatively positioned) section so it can never widen the page or spill into the next band
export const ContourLines: React.FC<ContourLinesProps> = ({ set = 'hill', tone = 'ink', className = '' }) => {
  const { viewBox, align, mobile, rings } = SETS[set];
  return (
    <div aria-hidden="true" className="pointer-events-none absolute inset-0 overflow-hidden">
      <svg
        focusable="false"
        viewBox={viewBox}
        preserveAspectRatio={`${align} meet`}
        className={`absolute ${TONE[tone]} ${className}`}
      >
        <g fill="none" stroke="currentColor" strokeWidth="1">
          {rings.map((d, i) => (
            <path key={d} d={d} vectorEffect="non-scaling-stroke" className={i >= mobile ? 'max-sm:hidden' : undefined} />
          ))}
        </g>
      </svg>
    </div>
  );
};
